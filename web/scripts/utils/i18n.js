function getLanguage() {
    const saved = settingsSync.get(LANG_KEY, null);
    return translations[saved] ? saved : DEFAULT_LANG;
}

function t(key) {
    const lang = getLanguage();
    return translations[lang]?.[key] ?? translations[DEFAULT_LANG]?.[key] ?? key;
}

function applyTranslations(root = document) {
    const lang = getLanguage();

    root.querySelectorAll?.('[data-i18n]').forEach(el => {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    root.querySelectorAll?.('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    root.querySelectorAll?.('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    // DaisyUI tooltips render from data-tip, not the title attribute.
    root.querySelectorAll?.('[data-i18n-tip]').forEach(el => {
        el.setAttribute('data-tip', t(el.getAttribute('data-i18n-tip')));
    });
    // Compact-rail nav items show their label via a CSS ::after reading data-label
    // (see .rail-item in app.css) rather than visible text, so translate that instead.
    // <optgroup> is the other element whose visible text is an attribute (`label`)
    // rather than textContent — data-i18n would silently insert a stray text node
    // instead of translating what the browser actually renders, so it shares this
    // same data attribute rather than getting its own.
    root.querySelectorAll?.('[data-i18n-label]').forEach(el => {
        const translated = t(el.getAttribute('data-i18n-label'));
        if (el.tagName === 'OPTGROUP') {
            el.setAttribute('label', translated);
        } else {
            el.setAttribute('data-label', translated);
        }
    });


    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('btn-primary', btn.dataset.lang === lang);
        btn.classList.toggle('btn-ghost', btn.dataset.lang !== lang);
    });
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    settingsSync.set(LANG_KEY, lang);
    applyTranslations();
    window.logger?.debug(CATEGORIES.SYSTEM, 'LanguageChanged', {lang});
    document.dispatchEvent(new CustomEvent('languageChanged', {detail: {lang}}));
}

const i18n = {getLanguage, setLanguage, t, applyTranslations};
export default i18n;
